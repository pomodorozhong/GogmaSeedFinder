export function pl(source, values = {}) {
  const locale = getLocale();
  const translated = locale === "ja" ? PLANNER_TEXT[source]?.[0] : locale === "zh-Hant" ? PLANNER_TEXT[source]?.[1] : source;
  return (translated ?? source).replace(/\{(\w+)\}/g, (_, key) => values[key] ?? `{${key}}`);
}
